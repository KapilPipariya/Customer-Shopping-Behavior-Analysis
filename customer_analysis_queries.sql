create database customer_behavior;
use customer_behavior;

CREATE TABLE Customer (
	Customer_ID int primary key,
	Age int,
    Gender VARCHAR(10),
    Item_Purchased VARCHAR(50),
    Category VARCHAR(50),
    Purchase_Amount int,
    Location VARCHAR(50),
    Size VARCHAR(5),
	Color VARCHAR(30),
    Season VARCHAR(20),
	Review_Rating decimal(2,1),
    Subscription_Status VARCHAR(10),
    Shipping_Type VARCHAR(30),
    Discount_Applied VARCHAR(10),
    Previous_Purchases INT,
    Payment_Method VARCHAR(30),
    Frequency_of_Purchases VARCHAR(30),
    Age_Group VARCHAR(20),
    Purchase_Frequency_Days int
);
select * from customer;
select * from customer limit 10;

-- Q1. What is the total revenue generated by male vs. female customers?
select gender, sum(Purchase_Amount) as Total_Revanue from customer 
group by gender order by Total_Revanue;

-- Q2. Which customers used a discount but still spent more than the average purchase amount?
select Customer_ID, Discount_Applied, Purchase_Amount from customer where Discount_Applied = "Yes" 
and Purchase_Amount >= (select avg(Purchase_Amount));
 
-- Q3. Which are the top 5 products with the highest average review rating?
select Item_Purchased, round(avg(Review_Rating),2) as "average product rating" from customer
group by Item_Purchased order by "average product rating" desc limit 5;

-- Q4. Compare the average Purchase Amounts between Standard and Express Shipping.
select Shipping_Type, round(avg(purchase_amount),2) as average_purchase_amount  from customer
where Shipping_Type in ('Standard','Express') group by Shipping_Type  ;
 
-- Q5. Do subscribed customers spend more? Compare average spend and total revenue 
-- between subscribers and non-subscribers.
select Subscription_Status, count(customer_id) as total_customer,
 round(avg(Purchase_Amount),2) as avg_spend, 
 round(sum(Purchase_Amount),2) as total_revenue
 from customer group by Subscription_Status ;

-- Q6. Which 5 products have the highest percentage of purchases with discounts applied?
SELECT item_purchased,
ROUND(100.0 * SUM(CASE WHEN discount_applied = 'Yes' THEN 1 ELSE 0 END)/COUNT(*),2)
 AS discount_rate FROM customer
GROUP BY item_purchased
ORDER BY discount_rate DESC
LIMIT 5;

-- Q7. Segment customers into New, Returning, and Loyal based on their total 
-- number of previous purchases, and show the count of each segment.
with customer_type as (
SELECT customer_id, previous_purchases,
CASE 
    WHEN previous_purchases = 1 THEN 'New'
    WHEN previous_purchases BETWEEN 2 AND 10 THEN 'Returning'
    ELSE 'Loyal'
    END AS customer_segment
FROM customer)
select customer_segment,count(*) AS "Number of Customers" 
from customer_type 
group by customer_segment;

-- Q8. What are the top 3 most purchased products within each category?
WITH item_counts AS (
    SELECT category,
           item_purchased,
           COUNT(customer_id) AS total_orders,
           ROW_NUMBER() OVER (PARTITION BY category ORDER BY COUNT(customer_id) DESC) AS item_rank
    FROM customer
    GROUP BY category, item_purchased
)
SELECT item_rank,category, item_purchased, total_orders
FROM item_counts
WHERE item_rank <=3;

-- Q9. Are customers who are repeat buyers (more than 5 previous purchases) also likely to subscribe?
SELECT subscription_status, COUNT(customer_id) AS repeat_buyers FROM customer
WHERE previous_purchases > 5
GROUP BY subscription_status;

-- Q10. What is the revenue contribution of each age group?
SELECT age_group, SUM(purchase_amount) AS total_revenue FROM customer
GROUP BY age_group ORDER BY total_revenue desc;